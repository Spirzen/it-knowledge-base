/** doc id → URL пути сайта */
export function collectionEntryPath(docId) {
  return `/${docId}`;
}

/** Первая статья подборки — точка входа в маршрут */
export function collectionStartPath(collection) {
  return collectionEntryPath(collection.items[0]);
}

export function articlesCountLabel(count) {
  if (count % 10 === 1 && count % 100 !== 11) {
    return `${count} статья`;
  }
  if (count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 10 || count % 100 >= 20)) {
    return `${count} статьи`;
  }
  return `${count} статей`;
}
